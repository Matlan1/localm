"""Write docs/models.md, the list of model kinds localm runs, from localm's own tables.

    python scripts/gen_models_page.py           # rewrite docs/models.md
    python scripts/gen_models_page.py --check   # exit 1 when docs/models.md is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from localm.inference.backends.llamacpp import _api  # noqa: E402
from localm.model_manager import gguf, registry  # noqa: E402
from localm.setup_llama import pins  # noqa: E402

PAGE = REPO / "docs" / "models.md"


def _names(items) -> str:
    return ", ".join(f"`{x}`" for x in sorted(items))


def render() -> str:
    tag = pins._PINNED_TAG
    arch_src = f"https://github.com/ggml-org/llama.cpp/blob/{tag}/src/llama-arch.cpp"
    music = sorted(gguf._GGUF_MUSIC_ARCHITECTURES)
    lines = [
        "# Supported models",
        "",
        "<!-- Generated by scripts/gen_models_page.py from localm's own tables. Do not edit by hand. -->",
        "",
        "localm runs models in these formats and roles. The lists below are the tables "
        "localm itself uses to decide what a model is, so this page and the program agree.",
        "",
        "## Chat and text",
        "",
        f"- **GGUF:** every text architecture the bundled llama.cpp build `{tag}` supports "
        f"([its list]({arch_src})), except the special roles below. Vision models load "
        "with their projector (`--mmproj`).",
        "- **Hugging Face Transformers:** models whose `config.json` names an architecture "
        f"ending in {_names(registry._HF_LLM_ARCH_SUFFIXES)}.",
        "- **EXL2 and EXL3:** through ExLlama (Linux with an NVIDIA GPU, the `exllama` extra).",
        f"- **Diffusion language models (GGUF):** {_names(gguf.GGUF_DIFFUSION_ARCHITECTURES)}.",
        f"- **Multi-token prediction drafting (GGUF):** {_names(_api.MTP_GRAPH_ARCHITECTURES)}.",
        "",
        "## Embeddings",
        "",
        f"- **GGUF:** {_names(gguf._GGUF_EMBEDDING_ARCHITECTURES)}.",
        "",
        "## Speech",
        "",
        f"- **Text to speech (GGUF):** {_names(gguf.GGUF_TTS_ARCHITECTURES)}.",
        "- **Speech to text:** Whisper (the `voice` extra).",
        "",
        "## Image and video",
        "",
        f"- **GGUF checkpoints:** {_names(gguf._GGUF_IMAGE_ARCHITECTURES)}, "
        "through the built-in stable-diffusion.cpp backend or ComfyUI.",
        f"- **Text encoders (GGUF):** {_names(gguf.GGUF_TEXT_ENCODER_ARCHITECTURES)}.",
        "",
        "## Music",
        "",
        f"- **ACE-Step (GGUF components):** {_names(music)}.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else ""
        if current != text:
            print("docs/models.md is out of date: run python scripts/gen_models_page.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
